function normOf(title: string | undefined): [number, number] | undefined {
  const t = (title ?? '').trim();
  if (!t) return undefined;
  for (const [re, lo, hi] of NORMS) if (re.test(t)) return [lo, hi];
  return undefined;
}

/** 그 자리의 현실 나이(같은 사람이면 늘 같은 값). 표에 없는 자리면 undefined */
export function ageForTitle(title: string | undefined, seed: string): number | undefined {
  const n = normOf(title);
  if (!n) return undefined;
  const [lo, hi] = n;
  return lo + (hashStr(`${seed}:age`) % (hi - lo + 1));
}

/** 받은 나이가 그 자리의 현실 범위에서 크게 벗어나면(스물다섯 살 부장 등) 범위 안으로 고친다. 표에 없는 자리면 그대로 */
export function fitAge(title: string | undefined, age: number | undefined, seed: string): number | undefined {
  const n = normOf(title);
  if (!n) return age;
  if (!age) return ageForTitle(title, seed);
  const [lo, hi] = n;
  return age < lo - 1 || age > hi + 4 ? ageForTitle(title, seed) : age;
}

